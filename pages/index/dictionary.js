const SUBJECT = { ME: 'I' };
const OBJECT = { HE: 'him', SHE: 'her', WE: 'us', THEY: 'them' };
const POSSESSIVE = new Set(['MY', 'YOUR', 'OUR']);
const BE = { I: 'am', you: 'are', we: 'are', they: 'are' };

export function lookup(gloss) {
  const entry = GLOSSES[gloss];
  return entry ? entry.english : String(gloss).toLowerCase();
}

// shortcut: a handful of word-order rules, not a parser; the LLM path handles everything else.
export function fallbackSentence(glosses) {
  const all = (glosses || []).map((g) => ({ g, pos: GLOSSES[g] && GLOSSES[g].pos, word: lookup(g) }));
  if (!all.length) return '';
  const time = all.filter((t) => t.pos === 'time').map((t) => t.word);
  let rest = all.filter((t) => t.pos !== 'time');
  const wh = rest.find((t) => t.pos === 'wh');
  rest = rest.filter((t) => t !== wh);
  const verbAt = rest.findIndex((t) => t.pos === 'verb');
  // "WANT COFFEE YOU" -> "Do you want coffee?": trailing YOU after a verb with no subject before it.
  const yesNo = !wh && verbAt >= 0 && rest.length > 1 && rest[rest.length - 1].g === 'YOU'
    && !rest.slice(0, verbAt).some((t) => t.pos === 'pron');
  if (yesNo) rest = rest.slice(0, -1);

  const words = rest.map((t, i) => {
    if (t.pos !== 'pron' || POSSESSIVE.has(t.g)) return t.word;
    if (verbAt < 0 && t.g === 'YOU' && rest[i + 1] && rest[i + 1].pos === 'noun') return 'your'; // "YOU NAME WHAT"
    return verbAt >= 0 && i > verbAt ? OBJECT[t.g] || t.word : SUBJECT[t.g] || t.word;
  });
  // A bare noun phrase gets "the" unless a pronoun/possessive already leads it.
  const the = rest[0] && rest[0].pos === 'noun' ? 'the ' : '';

  let body;
  if (wh && verbAt < 0) body = [wh.word, words.length ? 'is' : '', the + words.join(' ')];
  else if (wh) body = [wh.word, 'do', ...words];
  else if (yesNo) body = ['do you', ...words];
  else if (verbAt < 0 && rest.length > 1 && rest[rest.length - 1].pos === 'adj' && ['noun', 'pron'].includes(rest[rest.length - 2].pos)) {
    const subject = words.slice(0, -1);
    body = [the + subject.join(' '), BE[subject[subject.length - 1]] || 'is', words[words.length - 1]];
  } else body = words;

  const question = Boolean(wh) || yesNo;
  // Statements open with the time ("Tomorrow I go"); questions read better with it at the end.
  const text = (question ? [...body, ...time] : [...time, ...body]).filter(Boolean).join(' ').replace(/\s+/g, ' ').trim();
  return text.charAt(0).toUpperCase() + text.slice(1) + (question ? '?' : '.');
}
